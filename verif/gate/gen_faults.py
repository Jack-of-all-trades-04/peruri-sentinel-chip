"""Generate a stuck-at fault list for the gate-level fault campaign.

Usage:
  python3 gen_faults.py <core_gl.v> <tb_path_to_core_gl> <out_dir> [module ...]
  python3 gen_faults.py <core_gl.v> --map <module>=<tb path> ... <out_dir>

With --map, each listed module gets its faults at the given testbench path
(used for the unit testbenches); the fault ids are then local to that run,
and fault_report.py merges runs by (module, net, stuck value).

Reads the sky130 gate netlist, finds every standard-cell output net inside
the selected modules (default: the Sentinel security blocks and the core
glue logic, not the AES datapath), and writes:
  <out_dir>/faults.csv     id, instance path, net, stuck value, module
  <out_dir>/fault_inj.v    a module that forces fault +FAULT=<id> at time 0
Each net gets two faults: stuck-at-0 and stuck-at-1.
"""
import os
import re
import sys

OUT_PINS = {"X", "Y", "Q", "Q_N", "HI", "LO", "COUT", "SUM"}
DEFAULT = ["output_release_gate", "tamper_persist_fsm", "tripwire_zeroize",
           "master_key_vault", "dpa_hiding_lfsr", "peruri_sentinel_core_gl"]


def base(name):
    name = name.lstrip("\\")
    name = re.sub(r"^\$paramod(\$[0-9a-f]+)?\\", "", name)
    return name.split("\\")[0]


def parse(path):
    """Return {module_base: (module_name, [net, ...])} and top instance map."""
    mods, cur, nets, inst_of = {}, None, None, {}
    in_cell, top = False, None
    for line in open(path):
        s = line.strip()
        m = re.match(r"module\s+(\S+?)\s*\(", s)
        if m:
            cur = m.group(1)
            nets = []
            mods[base(cur)] = (cur, nets)
            continue
        if s.startswith("endmodule"):
            cur = None
            continue
        if cur is None:
            continue
        m = re.match(r"(\\?\S+)\s+(\S+)\s*\($", s)
        if m:
            typ = m.group(1)
            in_cell = typ.startswith("sky130_")
            if not in_cell and base(cur) == "peruri_sentinel_core_gl":
                inst_of[base(typ)] = m.group(2)
            continue
        m = re.match(r"\.(\w+)\((.+?)\),?$", s)
        if m and in_cell and m.group(1) in OUT_PINS:
            net = m.group(2).strip()
            if net not in nets:
                nets.append(net)
    return mods, inst_of


def main():
    netlist = sys.argv[1]
    pathmap = {}
    if sys.argv[2] == "--map":
        rest = sys.argv[3:]
        while rest and "=" in rest[0]:
            k, v = rest.pop(0).split("=", 1)
            pathmap[k] = v
        out, sel, tbpath = rest[0], list(pathmap), None
    else:
        tbpath, out = sys.argv[2], sys.argv[3]
        sel = sys.argv[4:] or DEFAULT
    mods, inst_of = parse(netlist)
    os.makedirs(out, exist_ok=True)
    rows = []
    for mb in sel:
        if mb not in mods:
            print(f"warning: module {mb} not in netlist", file=sys.stderr)
            continue
        _, nets = mods[mb]
        if pathmap:
            path = pathmap[mb]
        else:
            path = tbpath if mb == "peruri_sentinel_core_gl" else f"{tbpath}.{inst_of[mb]}"
        for net in nets:
            for v in (0, 1):
                rows.append((len(rows), path, net, v, mb))
    with open(os.path.join(out, "faults.csv"), "w") as f:
        f.write("id,path,net,stuck,module\n")
        for r in rows:
            f.write(",".join(str(x) for x in r) + "\n")
    with open(os.path.join(out, "fault_inj.v"), "w") as f:
        f.write("// generated by gen_faults.py: stuck-at fault selected by +FAULT=<id>\n")
        f.write("module fault_inj;\n    integer fid;\n    initial begin\n")
        f.write('        if (!$value$plusargs("FAULT=%d", fid)) fid = -1;\n')
        f.write("        case (fid)\n")
        for i, path, net, v, _ in rows:
            f.write(f"            {i}: force {path}.{net} = 1'b{v};\n")
        f.write("            default: ;\n        endcase\n    end\nendmodule\n")
    print(f"{len(rows)} faults in {len(sel)} modules")
    for mb in sel:
        n = sum(1 for r in rows if r[4] == mb)
        print(f"  {mb}: {n}")


if __name__ == "__main__":
    main()
